/**
 * Translation helper for landing page strings
 * @param {string} lang - 'en' | 'hi' | 'mr'
 * @param {string} path - dot-separated path (e.g. 'hero.primaryCta', 'registration.submit')
 * @returns {string} localized string, English fallback, or path
 */
export function t(lang, path) {
  if (!path || typeof path !== 'string') return '';
  const keys = path.split('.');
  let current = LANDING_STRINGS;

  for (const key of keys) {
    if (current && typeof current === 'object' && key in current) {
      current = current[key];
    } else {
      return path;
    }
  }

  if (current && typeof current === 'object') {
    return current[lang] ?? current['en'] ?? path;
  }

  if (typeof current === 'string') {
    return current;
  }

  return path;
}

